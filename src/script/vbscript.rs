const MAX_BLOCK_SIZE: usize = 10 * 1024 * 1024;

/// Decode each complete `#@~^...==...==^#~@` block.
pub(super) fn decode_blocks(input: &[u8]) -> Vec<(usize, String)> {
    const START: &[u8] = b"#@~^";
    const END: &[u8] = b"==^#~@";
    let mut out = Vec::new();
    let mut search = 0;

    while let Some(rel) = find_bytes(&input[search..], START) {
        let start = search + rel;
        let header_end = start + START.len() + 6;
        if input.get(header_end..header_end + 2) != Some(b"==") {
            search = start + START.len();
            continue;
        }
        let body_start = header_end + 2;
        let Some(end_rel) = find_bytes(&input[body_start..], END) else {
            break;
        };
        let marker_end = body_start + end_rel;
        // Six trailing checksum characters precede the `==^#~@` footer.
        if marker_end < body_start + 6 {
            search = marker_end + END.len();
            continue;
        }
        let body_end = marker_end - 6;
        if body_end - body_start <= MAX_BLOCK_SIZE {
            let decoded = decode_body(&input[body_start..body_end]);
            if !decoded.is_empty() {
                out.push((start, decoded));
            }
        }
        search = marker_end + END.len();
    }
    out
}

fn find_bytes(haystack: &[u8], needle: &[u8]) -> Option<usize> {
    haystack
        .windows(needle.len())
        .position(|window| window == needle)
}

fn decode_body(body: &[u8]) -> String {
    let mut out = String::with_capacity(body.len());
    let mut i = 0;
    let mut index = 0usize;
    while i < body.len() {
        let b = body[i];
        let escaped = if i + 1 < body.len() && body[i] == b'@' {
            match body[i + 1] {
                b'&' => Some((b'\n', 2)),
                b'#' => Some((b'\r', 2)),
                b'*' => Some((b'>', 2)),
                b'!' => Some((b'<', 2)),
                b'$' => Some((b'@', 2)),
                _ => None,
            }
        } else {
            None
        };
        let (mut ch, consumed) = escaped.unwrap_or((b, 1));
        if ch < 128 {
            index = index.wrapping_add(1);
        }
        if (ch == 9 || (ch > 31 && ch < 128)) && ch != b'<' && ch != b'>' && ch != b'@' {
            ch = DECODE[ch as usize][COMBINATION[(index - 1) % 64]];
        }
        out.push(char::from(ch));
        i += consumed;
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn decodes_real_encoded_asp_without_running_it() {
        let sample = crate::test_fixture("testdata/script/vbscript-encode.asp");
        let decoded = decode_blocks(sample);
        assert_eq!(decoded.len(), 1);
        assert_eq!(sample[decoded[0].0..].get(..4), Some(b"#@~^".as_slice()));
        assert!(decoded[0].1.contains("ExecuteGlobal request(\"LandGrey\")"));
    }

    #[test]
    fn decodes_multiple_blocks_and_preserves_offsets() {
        let sample = crate::test_fixture("testdata/script/vbscript-encode.asp");
        let mut input = sample.to_vec();
        input.extend_from_slice(sample);
        let decoded = decode_blocks(&input);
        assert_eq!(decoded.len(), 2);
        assert!(decoded[1].0 > decoded[0].0);
        assert_eq!(decoded[0].1, decoded[1].1);
    }

    #[test]
    fn ignores_missing_and_truncated_blocks() {
        assert!(decode_blocks(b"plain VBScript").is_empty());
        assert!(decode_blocks(b"#@~^IQAAAA==encoded without footer").is_empty());
        assert!(decode_blocks(b"#@~^IQAAA==not a six-byte header==^#~@").is_empty());
    }
}
